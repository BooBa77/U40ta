import { computed, ref } from 'vue'

/**
 * Счётчик занятости пользователя.
 *
 * Пока он больше нуля, PWA-обновление не применяется: перезагрузка
 * страницы посреди заполнения формы стёрла бы введённое. Разбор логики
 * целиком — в composables/useSwUpdate.js и App.vue.
 *
 * Состояние модульное, а не в Pinia: Pinia в это приложение не подключена,
 * а заводить её ради одного счётчика — лишняя сущность. Модульный ref
 * ровно так же один на всё приложение (модуль выполняется один раз),
 * а реактивность обеспечивает сам Vue.
 *
 * Счётчик, а не флаг: форма внутри модалки внутри страницы — обычное дело,
 * и с булевым флагом закрытие внутренней формы снимало бы занятость,
 * пока внешняя ещё открыта.
 */

/** Сколько источников занятости сейчас активно. */
const busyCount = ref(0)

/** Пользователь занят (заполняет форму, идёт сохранение). */
export const isUserBusy = computed(() => busyCount.value > 0)

/**
 * Пометить занятость (true) или освободить один источник (false).
 *
 * Ниже нуля не уходит: лишний setBusy(false) (например, двойное закрытие
 * формы) не должен «съедать» чужую занятость.
 */
export function setBusy(busy) {
  if (busy) busyCount.value++
  else busyCount.value = Math.max(0, busyCount.value - 1)
}

/** Сбросить счётчик целиком (аварийная мера). */
export function resetBusy() {
  busyCount.value = 0
}

/**
 * Выполнить асинхронное действие, удерживая счётчик занятости.
 *
 * Дыра, которую это закрывает: пользователь закончил правку, компонент
 * освободил счётчик, а запрос на сохранение ещё летит. Если в этот момент
 * придёт обновление, страница перезагрузится посреди запроса — и правка
 * потеряется.
 */
export async function whileBusy(action) {
  setBusy(true)
  try {
    return await action()
  } finally {
    setBusy(false)
  }
}

/** Композабл-обёртка: тот же API, что и у модульных функций. */
export function useAppBusy() {
  return { busyCount, isUserBusy, setBusy, resetBusy, whileBusy }
}
